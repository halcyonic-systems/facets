#!/usr/bin/env python3
"""The rename inventory (facets#541, phase 1): every occurrence of the old names, by class.

The project is Facets; the code still says bert. This script is the ledger the
rename epic is proved against: it walks the tree, finds every occurrence of an
old name, and files it under one class so each later phase can show its class
went to zero rather than claim it did.

  (no args)    walk the tree; write docs/rename/inventory-<date>.csv and the
               generated block of docs/rename/README.md; print the summary.
  --check      walk again and exit 1 if the CSV or the README block on disk
               differs from the fresh walk (the gate later phases run).
  --self-test  pin the classifier on scripts/fixtures/rename-inventory/ and the
               hand counts on three real files.
  --root DIR   inventory a different tree (used by the self-test).

Stdlib only, bare `python3`. Rows are one per occurrence (a line naming two
crates yields two rows), ordered by path, line, column. The `text` column is the
line, stripped and cut to 120 characters.

Names found. The token is `bert` on its own or with one of the crate suffixes,
any case, with `_` allowed on either side so `bert_lenses_kernel_bg.wasm` and
`CARGO_BIN_EXE_bert` count. `Bertalanffy`, `Hilbert` and `roberta` do not match.

Classes, in the order the rules fire; the first rule that applies wins.
  external-url   a URL carrying an old name (checked by HEAD in map.csv)
  format-tag     the saved-file format string `bert-lenses/canvas@1`
  lineage        docs/archive/, assets/archive/, docs/decisions/ (ADR record),
                 and the one history line in README, AGENTS and the notices
  upstream-bert  the BERT desktop app the crates were vendored from: `BERT`,
                 `halcyonic-systems/bert`, `old-bert`, a sibling `../bert`
                 checkout, the BERT-JSON variables in the audit scripts
  issue-ref      `bert-lenses#N` (this repo under its old name) and `bert#N`
  deploy         labels and paths outside the repo: launchd, ~/halcyonic-apps,
                 ~/Documents/bert-lenses, the pipeline user agent, the stale
                 bundle and process names in docs
  workflow       anything under .github/
  crate-dir      a path component `crates/bert-*`, `../bert-*`, `bert-*/src`
  import         `use bert_…` in Rust; `from "bert-lenses-kernel"` in TS/JS
  wasm-export    a wasm-bindgen export carrying the name (none today)
  package-name   `bert-lenses-web`, the wasm-pack output `bert_lenses_kernel`,
                 `bert-lenses-kernel` in a package manifest or build config
  golden         a JSON a BLESS_* variable re-mints (contract, CLI canonical,
                 demos, walkthroughs)
  fixture        any other file under fixtures/ or assets/ that is not prose
  cargo-name     `name = "bert-…"`, a `[dependencies]` key, `-p bert-cli`,
                 `--exclude bert-cli`, Cargo.lock, a crate name in Rust code
  rust-ident     `bert_core` … `bert_cli` in a .rs file
  cli-word       the `bert` binary: `bert run|bench|…`, `just bert`, the
                 `[[bin]]` name, `--bin bert`, bare `` `bert` `` in prose
  doc-prose      everything else: docs, READMEs, comments, SL comments

The walk uses `git ls-files` (tracked plus untracked-not-ignored) so build
output never enters the count, and skips the rename machinery itself
(docs/rename/, scripts/fixtures/rename-inventory/, this file).
"""

import argparse
import csv
import io
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INVENTORY_DATE = "2026-10-11"
RENAME_DIR = Path("docs") / "rename"
CSV_NAME = f"inventory-{INVENTORY_DATE}.csv"
README_NAME = "README.md"
SELF_TEST_TREE = Path("scripts") / "fixtures" / "rename-inventory"
SELF_TEST_EXPECTED = Path("scripts") / "fixtures" / "rename-inventory-expected.csv"

BEGIN = "<!-- rename-inventory:begin (generated by scripts/rename_inventory.py; do not edit) -->"
END = "<!-- rename-inventory:end -->"

CLASSES = [
    "external-url", "format-tag", "lineage", "upstream-bert", "issue-ref", "deploy",
    "workflow", "crate-dir", "import", "wasm-export", "package-name", "golden",
    "fixture", "cargo-name", "rust-ident", "cli-word", "doc-prose",
]

SKIP_DIRS = {".git", "node_modules", "target", "_site", "pkg", "pkg-probe", "dist", ".venv", "__pycache__", "runs"}
SKIP_PREFIXES = (str(RENAME_DIR) + "/", str(SELF_TEST_TREE) + "/", str(SELF_TEST_EXPECTED))
SKIP_FILES = {"scripts/rename_inventory.py", "scripts/rename_apply.py"}
BINARY_SUFFIXES = {".png", ".jpg", ".jpeg", ".gif", ".ico", ".icns", ".woff", ".woff2", ".ttf", ".otf", ".pdf", ".wasm", ".zip", ".gz"}

TOKEN = re.compile(
    r"(?<![A-Za-z0-9])bert"
    r"(?:(?:[-_]lenses(?:[-_](?:kernel|web|desktop|serve|pipeline))?|[-_](?:core|compose|canvas|tether|cli))(?![A-Za-z0-9])"
    r"|(?![A-Za-z0-9]|-[A-Za-z0-9]))",
    re.IGNORECASE,
)
URL_BEFORE = re.compile(r"https?://[^\s)>\"'`]*$")
LINEAGE_LINE = re.compile(r"until 2026-08-27|this codebase was|named `bert-lenses` until", re.IGNORECASE)
UPSTREAM_BEFORE = re.compile(r"(?:old|original|upstream|desktop)[- ]`?$|halcyonic-systems/$|\.\./$|-C $", re.IGNORECASE)
UPSTREAM_AFTER = re.compile(r"^(?:::|/)")
BINARY_PATH_BEFORE = re.compile(r"target/(?:debug|release)/$|--$")
CRATE_PATH_AFTER = re.compile(r"/(?:src|tests|pkg|pkg-probe|API\.md|Cargo\.toml|examples|docs)\b")
TS_IMPORT_BEFORE = re.compile(r"(?:from|import|require\()\s*[\"']$")
RS_IMPORT = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:use|extern crate)\s+bert_", re.IGNORECASE)
CARGO_KEY = re.compile(r"^\s*bert-[a-z-]+\s*=", re.IGNORECASE)
CARGO_NAME = re.compile(r"^\s*name\s*=\s*\"bert", re.IGNORECASE)
CARGO_FLAG_BEFORE = re.compile(r"(?:-p|--package|--exclude|cargo test -p)\s+$")
CLI_AFTER = re.compile(r"^\s+(?:run|bench|compile|verdict|describe|layout|--|\{|<|\*?ARGS|binary|CLI|exits|finishes|runs|fmt)\b")
CLI_BEFORE = re.compile(r"(?:just|--bin|CARGO_BIN_EXE_|\$ |cargo run [^#]*-- )$|`$")
PACKAGE_FILES = {"web/package.json", "web/package-lock.json", "web/vite.config.ts", "scripts/wasm_exec.mjs"}
GOLDEN_DIRS = ("fixtures/contract/", "fixtures/cli/", "assets/demos/", "assets/walkthroughs/")
C_LIKE = {".rs", ".ts", ".tsx", ".js", ".mjs", ".css"}
HASH_LIKE = {".py", ".sh", ".toml", ".yml", ".yaml", ".sl", ".plist", ""}


def tracked_files(root: Path) -> list[str]:
    """Every file git knows or would add, relative to root, sorted."""
    out = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
        capture_output=True, check=True,
    ).stdout.decode("utf-8", "surrogateescape")
    files = []
    for rel in out.split("\0"):
        if not rel:
            continue
        parts = rel.split("/")
        if SKIP_DIRS & set(parts):
            continue
        if rel.startswith(SKIP_PREFIXES) or rel in SKIP_FILES:
            continue
        if Path(rel).suffix.lower() in BINARY_SUFFIXES:
            continue
        if (root / rel).is_file():
            files.append(rel)
    return sorted(set(files))


def in_comment(ext: str, before: str, stripped: str) -> bool:
    if ext in C_LIKE:
        return "//" in before or stripped.startswith(("//", "*", "/*"))
    if ext in HASH_LIKE:
        return "#" in before.split("\"")[0] or stripped.startswith("#")
    return False


def in_string(before: str) -> bool:
    return (before.count("\"") - before.count("\\\"")) % 2 == 1


def classify(rel: str, line: str, start: int, end: int) -> str:
    tok = line[start:end]
    low = tok.lower()
    before = line[:start]
    after = line[end:]
    bare = low == "bert"
    parts = rel.split("/")
    ext = Path(rel).suffix.lower()
    stripped = line.lstrip()
    comment = in_comment(ext, before, stripped)

    if URL_BEFORE.search(before):
        return "external-url"
    if after.startswith("/canvas@"):
        return "format-tag"
    if rel.startswith(("docs/archive/", "assets/archive/", "docs/decisions/")):
        return "lineage"
    if bare and (BINARY_PATH_BEFORE.search(before) or ext == ".py" and (before.endswith("_") or after.startswith("_"))):
        return "cli-word"
    if tok == "BERT" or bare and (UPSTREAM_BEFORE.search(before) or UPSTREAM_AFTER.match(after)):
        return "upstream-bert"
    if LINEAGE_LINE.search(line):
        return "lineage"
    if bare and re.match(r"\s+`?[0-9a-f]{7,}\b", after):
        return "upstream-bert"
    if re.match(r"#\d", after):
        return "issue-ref"
    if (
        tok.isupper()
        or low.endswith(("-serve", "-desktop", "-pipeline"))
        or after.startswith(".app")
        or before.endswith(("com.halcyonic.", "halcyonic-apps/", "Documents/", "systems.halcyonic."))
    ):
        return "deploy"
    if parts[0] == ".github":
        return "workflow"
    if not bare and (before.endswith(("crates/", "../")) or CRATE_PATH_AFTER.match(after)):
        return "crate-dir"
    if ext in {".ts", ".tsx", ".js", ".mjs"} and TS_IMPORT_BEFORE.search(before):
        return "import"
    if ext == ".rs" and RS_IMPORT.match(line) and "_" in tok:
        return "import"
    if ext == ".rs" and rel.startswith("crates/bert-lenses-kernel/src/") and re.search(r"js_name|pub fn", before):
        return "wasm-export"
    if low == "bert-lenses-web" or low == "bert_lenses_kernel" and ext != ".rs":
        return "package-name"
    if low == "bert-lenses-kernel" and not comment and (rel in PACKAGE_FILES or before.endswith("crateVersion(\"")):
        return "package-name"
    if ext != ".md" and rel.startswith(GOLDEN_DIRS) and ext == ".json":
        return "golden"
    if ext != ".md" and parts[0] in {"fixtures", "assets"}:
        return "fixture"
    if not bare and (rel == "Cargo.lock" or ext == ".toml" and not comment and (CARGO_NAME.match(line) or CARGO_KEY.match(line))):
        return "cargo-name"
    if not bare and "-" in tok and CARGO_FLAG_BEFORE.search(before):
        return "cargo-name"
    if ext == ".rs" and not comment and "-" in tok:
        return "cargo-name" if after.startswith("\"") and before.endswith("\"") else "doc-prose"
    if ext == ".rs" and "_" in tok:
        return "rust-ident"
    if bare and (CLI_AFTER.match(after) or CLI_BEFORE.search(before) or after.startswith("`") or CARGO_NAME.match(line)):
        return "cli-word"
    if ext == ".rs" and bare and not comment and not in_string(before):
        return "rust-ident"
    if bare and tok == "bert":
        return "cli-word"
    return "doc-prose"


def inventory(root: Path) -> list[tuple[str, int, str, str]]:
    rows = []
    for rel in tracked_files(root):
        try:
            text = (root / rel).read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for no, line in enumerate(text.splitlines(), start=1):
            for m in TOKEN.finditer(line):
                rows.append((rel, no, classify(rel, line, m.start(), m.end()), line.strip()[:120]))
    return rows


def to_csv(rows) -> str:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["path", "line", "class", "text"])
    for r in rows:
        w.writerow(r)
    return buf.getvalue()


def top_dir(rel: str) -> str:
    parts = rel.split("/")
    return parts[0] + "/" if len(parts) > 1 else "(root)"


def table(headers, body) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(out)


def summary(rows, root: Path) -> str:
    by_class = Counter(r[2] for r in rows)
    by_dir = Counter(top_dir(r[0]) for r in rows)
    by_file = Counter(r[0] for r in rows)
    files_by_class = defaultdict(set)
    for r in rows:
        files_by_class[r[2]].add(r[0])
    parts = [f"Occurrences: **{len(rows)}** in **{len(by_file)}** files (inventory of {INVENTORY_DATE}, one row per occurrence).", ""]
    parts.append("### By class")
    parts.append("")
    parts.append(table(["class", "occurrences", "files"], [(c, by_class[c], len(files_by_class[c])) for c in CLASSES if by_class[c]]))
    parts.append("")
    parts.append("### By top-level directory")
    parts.append("")
    parts.append(table(["directory", "occurrences"], sorted(by_dir.items(), key=lambda kv: (-kv[1], kv[0]))))
    parts.append("")
    parts.append("### Files with the most occurrences")
    parts.append("")
    parts.append(table(["file", "occurrences"], sorted(by_file.items(), key=lambda kv: (-kv[1], kv[0]))[:20]))
    parts.append("")
    parts.append("### Phase 5: goldens and fixtures to re-bless")
    parts.append("")
    parts.append("Every `golden` and `fixture` row, by file. A golden is re-minted by its BLESS_* variable after phase 2 renames the crates; a fixture is edited by hand with its diff read.")
    parts.append("")
    rebless = Counter((r[0], r[2]) for r in rows if r[2] in {"golden", "fixture"})
    parts.append(table(["file", "class", "occurrences"], [(f, c, n) for (f, c), n in sorted(rebless.items())]))
    parts.append("")
    parts.append(f"{len(rebless)} files, {sum(rebless.values())} occurrences.")
    parts.append("")
    parts.append("### Phase 5 moves with phase 2: `docs/lean-manifest.json` `stated_in` paths naming a crate")
    parts.append("")
    manifest = root / "docs" / "lean-manifest.json"
    hits = []
    if manifest.is_file():
        for no, line in enumerate(manifest.read_text(encoding="utf-8").splitlines(), start=1):
            if '"stated_in"' in line:
                paths = re.findall(r"crates/bert-[a-z-]+/[A-Za-z0-9_./-]+", line)
                if paths:
                    hits.append((no, len(paths), ", ".join(f"`{p}`" for p in paths)))
    parts.append(table(["line", "paths", "which"], hits))
    parts.append("")
    parts.append(f"{len(hits)} `stated_in` lines, {sum(h[1] for h in hits)} crate paths. Gate A (`scripts/lean_provenance.py resolve`) reads these paths; they move in the same PR as the crate directories or the gate breaks.")
    return "\n".join(parts)


def replace_block(readme: str, block: str) -> str:
    if BEGIN not in readme or END not in readme:
        raise SystemExit(f"{RENAME_DIR / README_NAME}: missing the generated-block markers")
    head, rest = readme.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n\n{block}\n\n{END}{tail}"


def cmd_write(root: Path) -> int:
    rows = inventory(root)
    out_dir = root / RENAME_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / CSV_NAME).write_text(to_csv(rows), encoding="utf-8")
    block = summary(rows, root)
    readme = out_dir / README_NAME
    if readme.is_file():
        readme.write_text(replace_block(readme.read_text(encoding="utf-8"), block), encoding="utf-8")
    print(block)
    print(f"\nwrote {RENAME_DIR / CSV_NAME} ({len(rows)} rows)" + (f" and the generated block of {RENAME_DIR / README_NAME}" if readme.is_file() else ""))
    return 0


def cmd_check(root: Path) -> int:
    rows = inventory(root)
    csv_path = root / RENAME_DIR / CSV_NAME
    readme = root / RENAME_DIR / README_NAME
    failures = []
    on_disk = csv_path.read_text(encoding="utf-8") if csv_path.is_file() else ""
    if on_disk != to_csv(rows):
        disk_rows = list(csv.reader(io.StringIO(on_disk)))[1:]
        want = Counter(r[2] for r in disk_rows)
        got = Counter(r[2] for r in rows)
        for c in CLASSES:
            if want[c] != got[c]:
                failures.append(f"  {c}: on disk {want[c]}, fresh walk {got[c]}")
        failures.insert(0, f"{RENAME_DIR / CSV_NAME} differs from a fresh walk ({len(disk_rows)} rows on disk, {len(rows)} fresh):")
    if readme.is_file():
        text = readme.read_text(encoding="utf-8")
        if replace_block(text, summary(rows, root)) != text:
            failures.append(f"{RENAME_DIR / README_NAME}: generated block is stale")
    if failures:
        print("\n".join(failures), file=sys.stderr)
        print(f"\nrun `python3 scripts/rename_inventory.py` to regenerate (#541)", file=sys.stderr)
        return 1
    print(f"rename-inventory: OK — {len(rows)} occurrences match {RENAME_DIR / CSV_NAME}")
    return 0


# Hand counts, done by reading each file in full on 2026-10-11 (the phase 1
# proof asked for in #541). When a later phase changes one of these files the
# pin moves with it, with the new reading in that PR. Phase 2 moved the kernel
# crate and renamed its identifiers: lib.rs re-read in full, one occurrence
# left (line 1, the crate's old name in the header comment, phase 6). The same
# phase moved the crate paths in VENDORING.md (lines 15 and 47; the two
# revision-pinned show commands on lines 26 and 27 keep their revisions' paths)
# and the pkg path in web/package.json (line 20; the package names on lines 2
# and 20 are phase 3): both re-read in full. Phase 3 renamed those two
# package names; web/package.json re-read in full, none left. Phase 6 renamed
# the header line of lib.rs and the title of VENDORING.md; both re-read in full.
HAND_COUNTS = {
    "crates/facets-kernel/src/lib.rs": 0,
    "docs/VENDORING.md": 20,
    "web/package.json": 0,
}


def cmd_self_test(root: Path) -> int:
    tree = root / SELF_TEST_TREE
    expected = root / SELF_TEST_EXPECTED
    rows = inventory(tree)
    got = to_csv(rows)
    want = expected.read_text(encoding="utf-8")
    if got != want:
        print("self-test: classifier output differs from the expected fixture:", file=sys.stderr)
        for a, b in zip(want.splitlines(), got.splitlines()):
            if a != b:
                print(f"  want {a}\n  got  {b}", file=sys.stderr)
        if want.count("\n") != got.count("\n"):
            print(f"  row count: want {want.count(chr(10)) - 1}, got {got.count(chr(10)) - 1}", file=sys.stderr)
        return 1
    classes_seen = {r[2] for r in rows}
    missing = [c for c in CLASSES if c not in classes_seen and c != "wasm-export"]
    if missing:
        print(f"self-test: the synthetic tree exercises no row of class {missing}", file=sys.stderr)
        return 1
    real = Counter(r[0] for r in inventory(root))
    bad = {f: (n, real[f]) for f, n in HAND_COUNTS.items() if real[f] != n}
    if bad:
        for f, (want_n, got_n) in bad.items():
            print(f"self-test: {f}: hand count {want_n}, script {got_n}", file=sys.stderr)
        return 1
    print(f"self-test ok ({len(rows)} synthetic rows across {len(classes_seen)} classes; hand counts hold on {len(HAND_COUNTS)} files)")
    return 0


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="exit 1 if the inventory on disk differs from a fresh walk")
    p.add_argument("--self-test", action="store_true", help="pin the classifier on the synthetic tree and the hand counts")
    p.add_argument("--root", default=str(ROOT), help="tree to inventory (default: this repo)")
    p.add_argument("--stdout", action="store_true", help="print the CSV instead of writing anything")
    args = p.parse_args(argv)
    root = Path(args.root).resolve()
    if args.self_test:
        return cmd_self_test(root)
    if args.check:
        return cmd_check(root)
    if args.stdout:
        sys.stdout.write(to_csv(inventory(root)))
        return 0
    return cmd_write(root)


if __name__ == "__main__":
    raise SystemExit(main())
