#!/usr/bin/env node
/**
 * Generates shared/frost.css (+ shared/fonts/) — the Halcyonic Frost foundation
 * consumed by the static surfaces (portal/, chat/). web/src/index.css is the
 * single source of truth for every token value; this script EXTRACTS the
 * cross-app subset, so the two apps cannot drift. Same idiom as the homeostat
 * mirror: never hand-edit the output, edit index.css / fonts.css and re-run.
 *
 *   node scripts/gen-frost-shared.mjs           write shared/
 *   node scripts/gen-frost-shared.mjs --check   verify shared/ is current (CI)
 *
 * The subset is the base Frost register (surfaces, text, accents, verdicts,
 * structure, radii, shadows, the focus ring), the type scale (--t-*), the
 * printed-record register (paper/ink/rule/seal), the type stacks and motion.
 * Lens seams, KIND channels, chart series stay private to the model app — they
 * are kernel semantics, not foundation. The sheet also carries the three rules
 * every face shares: the focus ring, the reduced-motion gate, the wordmark.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, "..");
const INDEX_CSS = join(ROOT, "web/src/index.css");
const FONTS_CSS = join(ROOT, "web/src/fonts.css");
const FONTS_DIR = join(ROOT, "web/src/fonts");
const OUT_DIR = join(ROOT, "shared");
const OUT_CSS = join(OUT_DIR, "frost.css");

const SUBSET = [
  "// surfaces + text",
  "bg-primary", "bg-secondary", "bg-surface", "stage-from", "stage-to",
  "text-primary", "text-secondary", "text-muted", "text-on-accent",
  "// accents + verdicts",
  "accent", "accent-strong", "accent-soft", "accent-indigo", "accent-slate",
  "verdict-error", "verdict-warning", "verdict-ok",
  "// structure",
  "border", "rule-strong", "hairline",
  "radius-sm", "radius-md", "radius-lg", "radius-card", "radius-pill",
  "shadow-ink", "shadow-ink-hover", "shadow-card", "shadow-card-hover",
  "focus-ring",
  "// type scale (makeover rule 5): two families, eight sizes, one label tracking",
  "t-d1", "t-d2", "t-d3", "t-body", "t-sm", "t-num", "t-meta", "t-label", "tracking-label",
  "// printed record (paper register)",
  "paper", "paper-ground", "paper-edge",
  "ink", "ink-secondary", "ink-muted", "rule", "rule-soft", "seal",
  "// type + motion",
  "font-display", "font-body", "font-mono", "motion-fast", "motion", "transition-base",
];

// Rules every static face gets with the tokens (makeover rules 10, 13 and the
// one wordmark). They mirror the global rules in web/src/index.css; the app
// keeps its own copy because it does not link this sheet.
const SHARED_RULES = `
/* FOCUS (makeover rule 10): one ring, the accent, 2px, offset 2px, on every
   control under keyboard focus; nothing under pointer focus. A face may move
   the ring, never remove it. */
:focus-visible { outline: var(--focus-ring); outline-offset: 2px; }
:focus:not(:focus-visible) { outline: none; }

/* MOTION (makeover rule 13): under prefers-reduced-motion nothing animates,
   nothing loops and nothing eases. */
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after {
    animation-duration: 0.01ms !important;
    animation-iteration-count: 1 !important;
    transition-duration: 0.01ms !important;
  }
}

/* WORDMARK: one drawing on every face. Cormorant Garamond 700 "facets", the
   face name after it in the accent. Each surface sets only the size, from the
   --t-* scale (the portal hero scales --t-d1). */
.wordmark {
  font-family: var(--font-display); font-weight: 700; line-height: 1;
  letter-spacing: -0.01em; color: var(--text-primary); text-decoration: none;
}
.wordmark .face { color: var(--accent); }
`;

const src = readFileSync(INDEX_CSS, "utf8");
const decl = {};
for (const m of src.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
  if (!(m[1] in decl)) decl[m[1]] = m[2].trim(); // first hit = the :root value
}

const lines = [];
for (const name of SUBSET) {
  if (name.startsWith("// ")) {
    lines.push(`\n  /* ${name.slice(3)} */`);
    continue;
  }
  const v = decl[`--${name}`];
  if (!v) {
    console.error(`gen-frost-shared: --${name} not found in web/src/index.css`);
    process.exit(1);
  }
  lines.push(`  --${name}: ${v};`);
}

const fonts = readFileSync(FONTS_CSS, "utf8");

const out = `/*
 * GENERATED by scripts/gen-frost-shared.mjs — DO NOT EDIT.
 * Source of truth: web/src/index.css (tokens) + web/src/fonts.css (faces).
 * Change a value there, re-run the generator; portal + chat follow.
 *
 * Halcyonic Frost foundation for the static surfaces. Theming follows the
 * model app's doctrine: the palette is stated ONCE as light-dark() pairs and
 * color-scheme decides which half resolves — system by default, narrowed by
 * an explicit data-theme attribute if a surface ever grows a toggle.
 */

${fonts.trim()}

:root {
  color-scheme: light dark;
${lines.join("\n")}
}

:root[data-theme="light"] { color-scheme: light; }
:root[data-theme="dark"] { color-scheme: dark; }
${SHARED_RULES}`;

const check = process.argv.includes("--check");
if (check) {
  const current = existsSync(OUT_CSS) ? readFileSync(OUT_CSS, "utf8") : "";
  if (current !== out) {
    console.error("gen-frost-shared: shared/frost.css is stale — re-run scripts/gen-frost-shared.mjs");
    process.exit(1);
  }
  console.log("gen-frost-shared: shared/frost.css is current");
  process.exit(0);
}

mkdirSync(join(OUT_DIR, "fonts"), { recursive: true });
writeFileSync(OUT_CSS, out);
for (const f of readdirSync(FONTS_DIR)) copyFileSync(join(FONTS_DIR, f), join(OUT_DIR, "fonts", f));
console.log(`gen-frost-shared: wrote shared/frost.css (${SUBSET.filter((s) => !s.startsWith("// ")).length} tokens) + fonts/`);
