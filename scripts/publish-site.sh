#!/bin/bash
# Assembles the facets.systems site and pushes it to the `live` branch, which
# GitHub Pages serves. Publishing is DELIBERATE (branded-surface policy: no
# auto-publish from a working branch) — running this script IS the publish.
#
#   scripts/publish-site.sh               portal + chat; Model door "coming soon"
#   scripts/publish-site.sh --with-model  the canvas build at /, its entry the home page
#   scripts/publish-site.sh --dry-run     assemble only (tree left in _site/), no push
#
# Site layout (with model):  /  the canvas (wasm), whose entry page is the front
# door (Shingai, 2026-11-06) · /model/ a redirect to / for the links that
# predate it · /chat/ chat client · /docs/ the LIVE doc set rendered
# (scripts/build-docs.mjs, #368) · /shared/ Frost · 404.html
# Model dark: / is the portal (portal/index.html) with its Model door shut.
# The live branch is a snapshot (orphan commit, force-push) — never hand-edit it.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KERNEL_DIR="$REPO_ROOT/crates/facets-kernel"
WEB_DIR="$REPO_ROOT/web"
SITE_DIR="$REPO_ROOT/_site"
DOMAIN="facets.systems"

WITH_MODEL=0
DRY_RUN=0
for arg in "$@"; do
  case "$arg" in
    --with-model) WITH_MODEL=1 ;;
    --dry-run) DRY_RUN=1 ;;
    *) echo "unknown flag: $arg" >&2; exit 2 ;;
  esac
done

if [ $WITH_MODEL -eq 1 ]; then
  echo "==> Building wasm kernel"
  (cd "$KERNEL_DIR" && wasm-pack build --target web --out-dir pkg)
  echo "==> Building web frontend at base /"
  (cd "$WEB_DIR" && npm install && VITE_BASE=/ npm run build)
fi

echo "==> Assembling site tree"
rm -rf "$SITE_DIR"
mkdir -p "$SITE_DIR"
cp "$REPO_ROOT/portal/index.html" "$SITE_DIR/index.html"
rsync -a --exclude docs "$REPO_ROOT/chat/" "$SITE_DIR/chat/"
# Shared Frost foundation (generated — see scripts/gen-frost-shared.mjs);
# portal and chat link it at /shared/frost.css.
node "$REPO_ROOT/scripts/gen-frost-shared.mjs" --check
rsync -a "$REPO_ROOT/shared/" "$SITE_DIR/shared/"
# The docs (#368): the LIVE doc set rendered on every publish, model door or not.
[ -d "$WEB_DIR/node_modules/marked" ] || (cd "$WEB_DIR" && npm install)
node "$REPO_ROOT/scripts/build-docs.mjs" "$SITE_DIR/docs"
mv "$SITE_DIR/chat/404.html" "$SITE_DIR/404.html"   # Pages serves one 404 per site
echo "$DOMAIN" > "$SITE_DIR/CNAME"
if [ $WITH_MODEL -eq 1 ]; then
  # The canvas is the site root and its entry page the front door; the
  # portal is not served. /model/ stays as a redirect so the portal's, the
  # chat's and any outside link still land.
  rsync -a "$WEB_DIR/dist/" "$SITE_DIR/"
  mkdir -p "$SITE_DIR/model"
  cat > "$SITE_DIR/model/index.html" <<'HTML'
<!doctype html>
<meta charset="utf-8">
<meta http-equiv="refresh" content="0; url=/">
<link rel="canonical" href="https://facets.systems/">
<title>facets</title>
<p>The model moved to the front door: <a href="/">facets.systems</a>.</p>
HTML
fi

if [ $DRY_RUN -eq 1 ]; then
  echo "==> Dry run: tree assembled at $SITE_DIR (not pushed)"
  exit 0
fi

echo "==> Publishing snapshot to origin/live"
SHA=$(git -C "$REPO_ROOT" rev-parse --short HEAD)
# mktemp's empty file would be rejected by git as a corrupt index — hand git a
# fresh path instead and let it initialize the index itself.
TMP_INDEX=$(mktemp) && rm -f "$TMP_INDEX"
trap 'rm -f "$TMP_INDEX"' EXIT
# Build the snapshot commit with a scratch index so the session's working index
# is never touched (one repo, one index — parallel worktrees are live here).
TREE=$(cd "$SITE_DIR" && GIT_DIR="$REPO_ROOT/.git" GIT_INDEX_FILE="$TMP_INDEX" \
  git add -Af . >/dev/null && GIT_DIR="$REPO_ROOT/.git" GIT_INDEX_FILE="$TMP_INDEX" \
  git write-tree)
MODEL_NOTE=$([ $WITH_MODEL -eq 1 ] && echo "with model" || echo "model dark")
COMMIT=$(GIT_DIR="$REPO_ROOT/.git" git commit-tree "$TREE" \
  -m "site snapshot from $SHA ($MODEL_NOTE) — generated by publish-site.sh, never hand-edit")
git -C "$REPO_ROOT" push --force origin "$COMMIT:refs/heads/live"
echo "==> Live: https://$DOMAIN (snapshot $COMMIT from $SHA, $MODEL_NOTE)"
